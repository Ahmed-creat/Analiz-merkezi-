def main():
    toplam_soru = 0
    for konu_id, ders, topic_key, beceriler, sorular, kartlar in HAVUZLAR:
        govde = {
            "konu_id": konu_id,
            "sinif": 10,
            "ders": ders,
            "kaynak_dosya": "elle yazıldı (v35.3)",
            "topic_key": topic_key,
            "sorular": [],
            "flashcards": [],
        }
        for i, (metin, secenekler, dogru, cozum) in enumerate(sorular):
            govde["sorular"].append({
                "soru_id": f"{konu_id}_o{i+1:02d}",
                "alt_beceri": beceriler[0] if i < 5 else beceriler[1],
                "metin": metin,
                "secenekler": secenekler,
                "dogru_index": dogru,
                "cozum": cozum,
                "zorluk": "deneme",
            })
            govde["flashcards"].append({
                "id": f"{konu_id}_o{i+1:02d}:flashcard",
                "front": kartlar[i][0],
                "back": kartlar[i][1],
            })
        yol = os.path.join(CIKTI, konu_id + ".json")
        with io.open(yol, "w", encoding="utf-8") as f:
            json.dump(govde, f, ensure_ascii=False, indent=2)
            f.write("\n")
        toplam_soru += len(sorular)
        print(f"{konu_id}.json: {len(sorular)} soru, {len(kartlar)} flashcard")
    print(f"TOPLAM {len(HAVUZLAR)} havuz / {toplam_soru} soru")


